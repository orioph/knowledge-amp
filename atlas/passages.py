POS = ["yes","no","between","history","future","next"]
# The passage heuristic: how a reading moves from one position to the next.
MOVE = {
 "yes":"Find where yes stops being true.",
 "no":"Hold the no and the yes together.",
 "between":"Ask when this between began.",
 "history":"Carry the history forward a lifetime.",
 "future":"Take one step toward that future today.",
 "next":"The step taken becomes the next yes.",
}
out = {"date":"2026-11-20","positions":POS,"move":MOVE,
       "passages":[{"s":s,"t":t,**dict(zip(POS,v))} for (s,t),v in P.items()]}
